"""Browser acceptance checks against the compiled Uno app, not mocked state."""
import functools, http.server, json, os, shutil, threading, traceback, zipfile
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
ROOT = Path(__file__).resolve().parents[1]
QA = ROOT / 'qa'; QA.mkdir(exist_ok=True)
results = []; logs = []; page_errors = []
def check(name, condition=True):
    assert condition, name
    results.append({'name': name, 'passed': True})
    print('PASS', name, flush=True)
class Handler(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *args): pass
server = http.server.ThreadingHTTPServer(('127.0.0.1', 4173), functools.partial(Handler, directory=str(ROOT / 'dist')))
threading.Thread(target=server.serve_forever, daemon=True).start()
error = None
with sync_playwright() as p:
    executable = os.environ.get('CHROMIUM_EXECUTABLE') or shutil.which('google-chrome') or shutil.which('chromium')
    browser = p.chromium.launch(executable_path=executable, headless=True, args=['--no-sandbox'])
    context = browser.new_context(viewport={'width': 1440, 'height': 1100}, accept_downloads=True)
    page = context.new_page()
    page.on('console', lambda m: logs.append(m.type + ': ' + m.text))
    page.on('pageerror', lambda e: page_errors.append(str(e)))
    page.set_default_timeout(20000)
    try:
        page.goto('http://127.0.0.1:4173/', wait_until='networkidle')
        expect(page.locator('h1')).to_contain_text("Don't just run it.")
        check('Marketing page loads')
        page.screenshot(path=str(QA / '01-marketing-desktop.png'), full_page=True)
        page.get_by_role('link', name='Explore the gallery').click()
        expect(page.locator('.lesson-card')).to_have_count(3)
        check('Gallery includes one app and three learning paths', page.locator('.featured').count() == 1)
        page.locator('#gallery-search').fill('binding')
        expect(page.locator('.lesson-card')).to_have_count(1)
        page.locator('#gallery-search').fill('no-match-zz')
        expect(page.locator('.empty')).to_be_visible()
        page.get_by_role('button', name='Show everything').click()
        page.screenshot(path=str(QA / '02-gallery-desktop.png'), full_page=True)
        check('Gallery search and empty-state recovery')
        page.locator('.lesson-card').first.click()
        page.wait_for_selector('#runtime-status[data-status="live"]', timeout=90000)
        page.wait_for_function("document.querySelector('#runtime-revision').textContent.includes('STATE')")
        check('Real Uno WebAssembly runtime connects to host')
        page.locator('[data-action="tab"][data-value="experiment"]').click()
        page.locator('#title-input').fill('A title from the browser test')
        expect(page.locator('#watch-rendered')).to_have_text('A title from the browser test')
        check('OneWay binding updates the actual TextBlock')
        page.locator('[data-action="binding"][data-value="OneTime"]').click()
        expect(page.locator('#live-binding')).to_contain_text('OneTime')
        page.locator('#title-input').fill('The source changed again')
        expect(page.locator('#watch-source')).to_have_text('The source changed again')
        expect(page.locator('#watch-rendered')).to_have_text('A title from the browser test')
        check('OneTime exhibits real stale-view behavior')
        page.locator('[data-action="challenge-start"]').click()
        page.locator('[data-action="challenge-check"]').click()
        expect(page.locator('#check-results .fail').first).to_be_visible()
        check('Broken binding fails behavioral checks')
        page.locator('[data-action="binding"][data-value="OneWay"]').click()
        page.locator('[data-action="challenge-check"]').click()
        expect(page.locator('#check-results .pass')).to_have_count(2)
        expect(page.locator('.completion')).to_be_visible()
        check('Repaired binding passes two real control-value checks')
        page.screenshot(path=str(QA / '03-anatomy-desktop.png'), full_page=True)
        page.locator('[data-action="select"][data-value="servings"]').first.click()
        page.locator('#servings').fill('4')
        page.locator('#servings').dispatch_event('input')
        expect(page.locator('#watch-coffee')).to_have_text('72 g')
        expect(page.locator('#watch-water')).to_have_text('160 ml')
        check('Serving changes update C# derived properties')
        page.locator('[data-action="select"][data-value="save"]').first.click()
        page.locator('[data-action="save"]').click()
        expect(page.locator('#watch-saved')).to_have_text('true')
        expect(page.locator('#event-list')).to_contain_text('SaveCommand complete')
        check('Save trace reports actual ViewModel events')
        page.locator('[data-action="select"][data-value="title"]').first.click()
        page.locator('#title-input').fill('My exported morning')
        expect(page.locator('#watch-rendered')).to_have_text('My exported morning')
        page.locator('[data-action="continue"]').first.click()
        with page.expect_download() as got:
            page.locator('[data-action="export-project"]').click()
        path = QA / 'exported-project.zip'; got.value.save_as(str(path))
        with zipfile.ZipFile(path) as z:
            check('Export creates a valid project ZIP', z.testzip() is None)
            check('Export includes edited source', 'My exported morning' in z.read('src/Mise/RecipeViewModel.cs').decode())
            check('Export includes image and session snapshot', 'src/Mise/Assets/coffee.png' in z.namelist() and 'anatomy-session.json' in z.namelist())
        page.locator('#close-dialog').click()
        page.locator('[data-action="tab"][data-value="source"]').click()
        expect(page.locator('.code-card pre')).to_contain_text('Binding Title, Mode=OneWay')
        check('Inspector shows packaged source, separate from overrides')
        page.set_viewport_size({'width':390,'height':844})
        page.screenshot(path=str(QA / '04-anatomy-mobile.png'), full_page=True)
        check('Mobile lab has no horizontal page overflow', page.evaluate('document.documentElement.scrollWidth <= innerWidth'))
        page.goto('http://127.0.0.1:4173/#/')
        page.screenshot(path=str(QA / '05-marketing-mobile.png'), full_page=True)
        check('Mobile marketing has no horizontal page overflow', page.evaluate('document.documentElement.scrollWidth <= innerWidth'))
        check('No uncaught browser errors', not page_errors)
    except Exception as ex:
        error = str(ex)
        results.append({'name':'browser acceptance run', 'passed':False, 'error':error})
        print(traceback.format_exc(), flush=True)
        page.screenshot(path=str(QA / 'failure.png'), full_page=True)
        (QA / 'failure.html').write_text(page.content(), encoding='utf-8')
        for i,frame in enumerate(page.frames):
            try: (QA / f'frame-{i}.html').write_text(frame.content(), encoding='utf-8')
            except Exception: pass
    finally:
        (QA / 'results.json').write_text(json.dumps({'checks':results,'pageErrors':page_errors,'success':error is None},indent=2))
        (QA / 'browser.log').write_text('\n'.join(logs+page_errors),encoding='utf-8')
        browser.close()
server.shutdown()
if error: raise SystemExit(1)
